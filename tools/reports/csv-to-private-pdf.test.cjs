const test = require('node:test')
const assert = require('node:assert/strict')
const { parseCsv, createHtml, escapeHtml } = require('./csv-to-private-pdf.cjs')
test('quoted CSV fields and Unicode survive parsing without executing markup', () => {
  const rows = parseCsv('\uFEFFname,score,note\r\n"A, B","9","<script>alert(1)</script>"\r\n"सीमा","8","He said ""hi"""\r\n')
  assert.equal(rows.length, 3)
  assert.equal(rows[1][0], 'A, B')
  assert.equal(rows[2][0], 'सीमा')
  assert.equal(rows[2][2], 'He said "hi"')
  const html = createHtml(rows, 'daily')
  assert.ok(html.includes('सीमा'))
  assert.ok(html.includes('&lt;script&gt;'))
  assert.ok(!html.includes('<script>alert(1)</script>'))
})
test('private rendering escapes HTML and enforces shape limits', () => {
  assert.equal(escapeHtml('a&<b>"'), 'a&amp;&lt;b&gt;&quot;')
  assert.throws(() => parseCsv('"unterminated'), /Unterminated/)
  assert.throws(() => createHtml([], 'monthly'), /no header/)
  assert.throws(() => createHtml([Array.from({length: 21}, (_, i) => String(i))], 'monthly'), /too many columns/)
})
