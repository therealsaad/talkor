import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { test } from 'node:test'
const read = (name) => readFile(new URL(name, import.meta.url), 'utf8')

const login = await read('../../app/login/student/page.tsx')
const loginLayout = await read('../../app/login/layout.tsx')
const resume = await read('../../app/student/continue/page.tsx')
const map = await read('../../components/student/kg-adventure-map.tsx')
const mapPage = await read('../../app/student/kg/map/page.tsx')
const level1 = await read('../../features/lessons/grades/kg/level-01/LevelExperience.tsx')
const nextPage = await read('../../app/student/kg/level-2/page.tsx')
const level2 = await read('../../features/lessons/grades/kg/level-02/StudentExperience.tsx')
const nextService = await read('../../features/lessons/grades/kg/level-02/services/kg-level2-student-service.ts')
const preview = await read('../../features/lessons/grades/kg/level-02/LevelExperience.tsx')
const backend = await read('../../../backend/src/controllers/kg-level2-student.controller.ts')
const routes = await read('../../../backend/src/routes/kg-level2-student.routes.ts')

test('PIN login uses the authenticated server resume route, no client-selected level or old E–J draft', () => {
  assert.match(login, /await loginStudentByPin\(pin\)/)
  assert.match(loginLayout, /homeForRole\(role\)/)
  assert.match(resume, /kgAlphabetService.state\(\)/)
  assert.match(resume, /kgLevel2StudentService.state\(\)/)
  assert.match(resume, /level1.completed && level1.level2Available|!level1.completed \|\| !level1.level2Available/)
  assert.match(resume, /level2.completed \? '\/student\/kg\/map' : '\/student\/kg\/level-2'/)
  assert.doesNotMatch(resume, /localStorage|sessionStorage/)
  assert.match(map, /number === 2 && kgLevel1State\?\.completed/)
  assert.match(map, /\/student\/kg\/level-2/)
  assert.match(mapPage, /kgLevel2StudentService.state\(\)/)
  assert.match(level1, /router.replace\('\/student\/kg\/level-2'\)/)
  assert.match(nextPage, /kgLevel2StudentService.state\(\)/)
  assert.match(nextPage, /kgLevel2StudentService.beginIntro\(\)/)
  assert.doesNotMatch(nextPage, /LEVEL2_INTRO_COMPLETED_KEY|\/school\/kg-preview/)
})

test('Level 2 is a separate authenticated student pilot; staff draft remains unpublishable', () => {
  assert.match(preview, /Staff-only draft preview/)
  assert.match(routes, /router.use\(authenticate, kgLessonLimiter, requireRole\('STUDENT'\)\)/)
  assert.match(backend, /KGAlphabetProgress.findOne\(\{ studentId: student._id, schoolId: student.schoolId \}\)/)
  assert.match(backend, /if \(kg1\?\.currentIndex !== 8\)/)
  assert.match(backend, /gradeLevel2Transcription/)
  assert.match(backend, /introGuard/)
  assert.match(backend, /verifyKGFeedbackReceipt/)
  assert.match(backend, /currentIndex: attempt.index/)
  assert.match(nextPage, /Level2PreviewIntro/)
  assert.match(nextService, /X-KG-Level2-Intro/)
  assert.match(nextService, /audio.onended = \(\) => \{ clean\(\); resolve\(\) \}/)
  assert.match(nextService, /heardReceipts.set\(submissionId, receipt\)/)
  assert.match(nextService, /heardReceipts.get\(submissionId\)/)
  assert.match(level2, /requestKGMicrophone\(controller.signal\)/)
  assert.match(level2, /watchVoiceActivity\(stream,/)
  assert.match(level2, /kgLevel2StudentService.acknowledge\(/)
  assert.doesNotMatch(level2, /previewSubmit|kg-level2-preview\/attempt/)
})
