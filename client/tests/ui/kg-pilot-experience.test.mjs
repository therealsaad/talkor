/* Source-level regression contracts for CURRENT October 19 KG flow. Not a browser or cloud smoke test. */
import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { test } from 'node:test'
const read=(file)=>readFile(new URL(file,import.meta.url),'utf8')
const login=await read('../../app/login/student/page.tsx')
const layout=await read('../../app/student/layout.tsx')
const map=await read('../../components/student/kg/kg-alphabet-map.tsx')
const lesson=await read('../../app/student/kg/page.tsx')
const service=await read('../../services/kg-alphabet-service.ts')
const controller=await read('../../../backend/src/controllers/kg-alphabet.controller.ts')
const routes=await read('../../../backend/src/routes/kg-alphabet.routes.ts')

test('KG PIN login goes directly to Level 1; map is only for replay',()=>{
 assert.match(login,/signedIn\.student\?\.grade === 0 \? '\/student\/kg'/)
 assert.match(map,/Optional replay map/)
 assert.match(map,/state\.completed \? 'Replay Level 1/)
 assert.match(map,/Level \$\{n\+2\} not yet published/)
 assert.match(layout,/mustKeepKGStudentInGarden/)
})
test('every KG visit starts a server watch ticket; there is no bypass button',()=>{
 assert.match(lesson,/const INTRO_VIDEO = '\/kg\/videos\/fullkg\.mp4'/)
 assert.match(lesson,/kgAlphabetService\.beginIntro\(\)/)
 assert.match(lesson,/kgAlphabetService\.introSeen\(\)/)
 assert.match(lesson,/onEnded=\{\(\) => \{/)
 assert.match(lesson,/introEndedRef\.current = true; void finishIntro\(\)/)
 assert.doesNotMatch(lesson,/Skip introduction|skip-intro|onClick=\{skipIntro\}/i)
 assert.match(controller,/INTRO_MINIMUM_MS = 59_000/)
 assert.match(controller,/req\.body\?\.videoEnded !== true/)
})
test('Azure TTS speech clips, corrected feedback and real microphone are connected',()=>{
 assert.match(routes,/KGAlphabetController\.audio/)
 assert.match(controller,/sendKGVoice/)
 assert.match(controller,/spokenFeedback/)
 assert.match(service,/previewSubmitPrepared/)
 assert.match(service,/playFeedback/)
 assert.match(lesson,/kgAlphabetService\.play/)
 assert.match(lesson,/requestKGMicrophone/)
 assert.match(lesson,/new MediaRecorder/)
 assert.match(lesson,/KGAlphabetService|kgAlphabetService\.submitPrepared/)
 assert.match(lesson,/silenceForMicrophone\(\)/)
 assert.match(lesson,/Please allow microphone access/)
})
test('fullscreen exit pauses story; error keeps retry path',()=>{
 assert.match(lesson,/requestFullscreen\(\{ navigationUI: 'hide' \}\)/)
 assert.match(lesson,/document\.addEventListener\('fullscreenchange', fullscreenChanged\)/)
 assert.match(lesson,/video\.pause\(\)/)
 assert.match(lesson,/controls=\{false\}/)
 assert.match(lesson,/onSeeking=\{keepVideoUnskippable\}/)
 assert.match(lesson,/setPhase\('intro-paused'\)/)
 assert.match(lesson,/retryVideo/)
})
